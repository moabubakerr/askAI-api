"""The corpus, answered -- the gate that says whether a question gets the right outcome.

``tests/corpus_runner.py`` compiles every entry against a **deliberately empty catalogue**
and asserts the binder's own properties: compiling is total, every field is bound once
with its precedence recorded, and the same question compiles identically on every run. It
never reads ``expected:``, never executes, and never checks whether a question is
answered.

So until this file existed, **nothing in this repository measured whether the engine
answers anything**. That is not a hypothetical gap. On 2026-09-17 a build that answered 9
of 95 corpus questions passed all five gates for days, and three separate defects reached
the target VM: an execution layer that produced one shape, a resolution ladder that was
never wired, and a catalogue that offered the home country as a filterable name. Every one
of them was found by running questions by hand.

**What this asserts.** Each corpus entry's question, through the real answer path, against
a real ingested estate, and the resulting package ``kind`` compared with the entry's
``expected``. Nothing more: this is the coarsest useful assertion, and it is worth having
because the three defects above all changed a ``kind``.

**What this does not assert, and must not be read as.** A ``kind`` of ``answer`` can still
be the *wrong* answer. ``e1-005`` ("What percentage of Qatar's energy is generated by
solar?") answers with *"Energy was 130.90 Index Points"* -- an unrelated indicator matched
on the bare word ``energy``. ``e5-012`` asks which periods are available and gets a
figure. Both would satisfy a ``kind`` comparison. Asserting on the composed text is the
next increment of this gate, not a replacement for it.

**Some entries pass for the wrong reason, and the gate cannot tell.** ``e6-002`` ("Why
did inflation move in April 2026?") expects an answer and gets one -- the bare figure,
not the analyst note it is asking for, so it will keep passing when Session U makes it
answer properly. ``e7-004`` and ``e6-005`` expect refusals and get them because the
feature does not exist at all. A passing row here means the outcome matched, never that
the answer was right.

**The ladder is deliberately off here.** ``engine_for`` is called without a
``CandidatePort``, so only exact published-name matching runs. That keeps this gate
deterministic and runnable with no embedding endpoint (NFR-6). It also means the numbers
here are the floor: a deployment with an index generation answers more, and differently.
Retrieval quality is measured by the AD-30 harness, not by this file.

**``KNOWN_GAPS`` is the point of the design.** A gate that is red everywhere is ignored, so
the entries that do not yet reach their expected outcome are listed with the reason and
the session that owns each. The list is asserted to be *exact*: an entry that starts
passing fails this suite until it is removed. That is deliberate -- it makes the list
shrink, and it makes a fix impossible to land silently.
"""

