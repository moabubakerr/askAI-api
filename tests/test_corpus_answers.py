@pytest.fixture(scope="module")
def databases() -> Iterator[Databases]:
    with provision() as estate:
        ingest_published_layer(estate.read_model, CmsExport.rooted(EXPORT_ROOT))
        yield estate


@pytest.fixture(scope="module")
def state_file(tmp_path_factory: pytest.TempPathFactory) -> Path:
    return tmp_path_factory.mktemp("estate") / "refresh_state.json"


def _entries() -> list[tuple[str, str, str, str]]:
    """``(id, question, expected, today)`` for every corpus entry with English text.

    English only, deliberately: this gate is about whether the engine reaches an outcome,
    and ``tests/test_bilingual_parity.py`` already owns the claim that both languages say
    the same thing. One entry (``e10-002``) carries no English text at all, which is an
    authoring slip recorded in ``sessions/session-n-deploy-and-verify.md``.
    """
    found: list[tuple[str, str, str, str]] = []
    for path in sorted(glob.glob(str(PROJECT_ROOT / "corpus" / "*.yaml"))):
        for entry in yaml.safe_load(Path(path).read_text(encoding="utf-8")) or []:
            if not isinstance(entry, dict) or "question" not in entry:
                continue
            asked = entry["question"]
            english = asked.get("en") if isinstance(asked, dict) else asked
            if not english:
                continue
            when = entry.get("today") or DEFAULT_TODAY
            found.append(
                (
                    str(entry.get("id", "")),
                    str(english).strip(),
                    str(entry.get("expected", "answer")),
                    when.isoformat() if isinstance(when, date) else str(when),
                )
            )
    return found


CORPUS: Final = _entries()


def _outcome(databases: Databases, state_file: Path, question: str, when: str) -> str:
    moment = datetime.fromisoformat(f"{when}T12:00:00+00:00").astimezone(UTC)
    engine = engine_for(databases, state_file, now=lambda: moment)
    answered = answer_question(
        engine,
        Ask(question=question, lang=Lang.EN, sources=SourceAdmission.APPROVED_ONLY),
    )
    return answered.response.packages[0].kind.value


def test_the_corpus_has_entries() -> None:
    """A guard on the loader: a glob that silently matched nothing would make every
    assertion below vacuous, and the suite would go green by finding no work."""
    assert len(CORPUS) > 90


@pytest.mark.parametrize(
    ("identifier", "question", "expected", "when"),
    [pytest.param(*row, id=row[0] or row[1][:40]) for row in CORPUS],
)
def test_the_corpus_entry_reaches_its_expected_outcome(
    databases: Databases,
    state_file: Path,
    identifier: str,
    question: str,
    expected: str,
    when: str,
) -> None:
    outcome = _outcome(databases, state_file, question, when)
    if identifier in KNOWN_GAPS:
        pytest.skip(f"known gap -- {KNOWN_GAPS[identifier]}")
    assert outcome == expected, (
        f"{identifier}: asked {question!r} expecting a {expected}, got a {outcome}. "
        "If this is a deliberate change, the corpus entry is what states the intent -- "
        "change it there, with a `why`, rather than here."
    )


def test_the_known_gaps_are_exactly_the_failures(
    databases: Databases, state_file: Path
) -> None:
    """The gap list is exact in both directions, and the second one is the point.

    An entry that has started passing must be **removed** from ``KNOWN_GAPS``, and this
    test fails until it is. Without that, a list written once decays into a list of
    things nobody has checked since, and a fix lands without anyone noticing it landed.
    """
    fixed: list[str] = []
    newly_broken: list[str] = []
    for identifier, question, expected, when in CORPUS:
        outcome = _outcome(databases, state_file, question, when)
        if identifier in KNOWN_GAPS and outcome == expected:
            fixed.append(f"{identifier} ({KNOWN_GAPS[identifier]})")
        if identifier not in KNOWN_GAPS and outcome != expected:
            newly_broken.append(f"{identifier}: expected {expected}, got {outcome}")

    assert not fixed, (
        "these entries now reach their expected outcome -- delete them from KNOWN_GAPS:\n  "
        + "\n  ".join(fixed)
    )
    assert not newly_broken, (
        "these entries regressed and are not listed as known gaps:\n  "
        + "\n  ".join(newly_broken)
    )
