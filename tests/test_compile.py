def test_no_call_site_constructs_a_country_filter_containing_the_home_country() -> None:
    """The AC's own words, asserted over the whole package rather than over ``domain/``.

    The literal is spelled by folding it from its own letters, so this test can assert
    the absence without being the one file that contains it.

    One exemption, the same one ``tests/test_domain_invariants.py`` argues for: the root
    package docstring says what the product is for, in prose, and holds no code. Naming
    the country in a sentence is not the defect; constructing a filter from it is.
    """
    home = normalise("".join(chr(point) for point in (0x51, 0x61, 0x74, 0x61, 0x72)))
    offenders = [
        f"{path.relative_to(PACKAGE_ROOT).as_posix()}:{node.lineno}"
        for path, tree in _modules(PACKAGE_ROOT)
        if path.relative_to(PACKAGE_ROOT).as_posix() != "__init__.py"
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and home in normalise(node.value)
    ]
    assert not offenders, "the home country is named as a literal: " + ", ".join(offenders)


