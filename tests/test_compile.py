# ------------------------------------------------------- FR-4, FR-5, FR-6: grain


def test_a_grain_named_in_the_question_wins_over_the_declared_default() -> None:
    """FR-4. Inflation declares monthly; the question says yearly, so it is yearly."""
    assert period_of("What was yearly inflation?") == Deferred(
        LastN(n=readings_for_latest(), grain=Grain.YEARLY)
    )


def test_a_grain_named_in_the_question_wins_over_the_period_it_inherited() -> None:
    """FR-4 through a follow-up: "and monthly?" moves the grain and nothing else."""
    account = compiled("And monthly?", history=("What was inflation in 2026-Q1?",))
    assert account.spec.detail == Bound("D-INFLATION")
    assert account.spec.period == Deferred(LastN(n=readings_for_latest(), grain=Grain.MONTHLY))
    assert account.by_field[SpecField.PERIOD].precedence is Precedence.NAMED_IN_QUESTION
    assert account.by_field[SpecField.DETAIL].precedence is Precedence.INHERITED_FROM_HISTORY


def test_the_arabic_follow_up_moves_the_grain_the_same_way() -> None:
    account = compiled("وشهرياً؟", history=("كم بلغ معدل التضخم في الربع الأول من 2026؟",))
    assert account.spec.period == Deferred(LastN(n=readings_for_latest(), grain=Grain.MONTHLY))


def test_a_period_phrase_implying_a_grain_counts_as_naming_one() -> None:
    """FR-5's second half: "April 2026" names monthly as surely as the word "monthly"."""
    assert period_of("What was inflation in April 2026?") == Bound(Exact(Period("2026-04")))
    assert period_of("What was inflation in the first quarter of 2026?") == Bound(
        Exact(Period("2026-Q1"))
    )
    assert period_of("What was Real GDP in 2025?") == Bound(Exact(Period("2025")))


def test_with_no_grain_named_the_detail_s_declared_default_is_used() -> None:
    """FR-5. Real GDP declares yearly even though it also publishes quarterly."""
    assert period_of("What is Real GDP now?") == Deferred(
        LastN(n=readings_for_latest(), grain=Grain.YEARLY)
    )
    assert period_of("What is inflation now?") == Deferred(
        LastN(n=readings_for_latest(), grain=Grain.MONTHLY)
    )


def test_the_declared_default_is_asked_of_the_catalogue_not_of_the_data() -> None:
    """FR-5's whole content: *not* the grain of the latest row.

    The catalogue here declares yearly for a detail that publishes quarterly as well, so
    a binder reading the newest row would have to answer quarterly to be wrong -- and it
    has no way to read one, which is the port's doing.
    """
    declared = CATALOGUE.default_grain("D-REAL-GDP")
    assert declared is Grain.YEARLY
    assert Grain.QUARTERLY in CATALOGUE.published_grains("D-REAL-GDP")


def test_a_detail_declaring_no_default_leaves_latest_ungrained() -> None:
    """``Latest`` carries no grain, and inventing one would be compile choosing a grain
    the catalogue never declared."""
    assert period_of("What is the percentage of energy generated by solar now?") == Deferred(
        Latest()
    )


def test_a_grain_the_detail_does_not_publish_is_stated_and_never_substituted() -> None:
    """FR-6. Real GDP publishes quarterly and yearly; monthly is refused as monthly."""
    state = period_of("What was monthly Real GDP?")
    assert isinstance(state, Unbound)
    assert state.reason.startswith(UnboundReason.GRAIN_NOT_PUBLISHED.value)
    assert Grain.MONTHLY.value in state.reason
    assert Grain.QUARTERLY.value in state.reason and Grain.YEARLY.value in state.reason


def test_a_named_period_at_an_unpublished_grain_is_refused_too() -> None:
    """The grain arrives inside the period, and it is refused the same way -- a quarter
    is never answered with the year that contains it."""
    state = period_of("What was Real GDP in April 2025?")
    assert isinstance(state, Unbound)
    assert state.reason.startswith(UnboundReason.GRAIN_NOT_PUBLISHED.value)


def test_a_grain_is_never_checked_against_a_detail_that_is_not_bound() -> None:
    """With no detail there is nothing to publish a grain, so the period still binds."""
    account = compiled("What was the monthly price of tea?")
    assert isinstance(account.spec.detail, Unbound)
    assert account.spec.period == Deferred(LastN(n=readings_for_latest(), grain=Grain.MONTHLY))


def test_more_than_one_named_period_is_unbound_rather_than_guessed() -> None:
    """A span is Epic 3's; two periods named here are an ambiguity, not a range to infer."""
    state = period_of("What was inflation between 2019 and 2025?")
    assert isinstance(state, Unbound)
    assert state.reason.startswith(UnboundReason.MORE_THAN_ONE_PERIOD_NAMED.value)


def test_a_month_with_no_year_names_no_period() -> None:
    """Picking the year would be compile inventing a period the reader never named."""
    assert period_of("What was inflation in April?") == Deferred(
        LastN(n=readings_for_latest(), grain=Grain.MONTHLY)
    )


