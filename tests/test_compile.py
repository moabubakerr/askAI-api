def compiled(question: str, *, history: tuple[str, ...] = ()) -> CompiledQuestion:
    return compile_question(
        CompileInput(question=question, today=TODAY, history=history), CATALOGUE
    )


def period_of(question: str, *, history: tuple[str, ...] = ()) -> object:
    return compiled(question, history=history).spec.period


def _modules(root: Path) -> list[tuple[Path, ast.Module]]:
    return [
        (path, ast.parse(path.read_text(encoding="utf-8"), filename=str(path)))
        for path in sorted(root.rglob("*.py"))
    ]


# ------------------------------------------------- AD-1: one spec, frozen, before data


def test_exactly_one_query_spec_is_constructed_in_the_whole_tree() -> None:
    """"Produced exactly once per answerable question" needs one producer, not a habit.

    A second construction site is how a field comes to be set twice -- the AD-1 defect
    arriving as a helper rather than as a decision. The scan finds the call, not the
    import, so re-exporting the type stays free.
    """
    sites = [
        f"{path.relative_to(PACKAGE_ROOT).as_posix()}:{node.lineno}"
        for path, tree in _modules(PACKAGE_ROOT)
        for node in ast.walk(tree)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Name)
        and node.func.id == QuerySpec.__name__
    ]
    assert len(sites) == 1, "a QuerySpec is constructed in more than one place: " + ", ".join(
        sites
    )
    assert sites[0].startswith("compile/binder.py:"), f"a QuerySpec is built in {sites[0]}"


def test_no_layer_past_compile_can_set_a_field() -> None:
    """The frozen type, asserted rather than assumed.

    There is no setter to forbid, so the assertion is that assignment itself fails --
    on every bindable field, so that a field added later without ``frozen`` is caught.
    """
    spec = compiled("What was inflation in April 2026?").spec
    for field in bindable_fields():
        with pytest.raises(dataclasses.FrozenInstanceError):
            setattr(spec, field, Unbound(reason="rewritten downstream"))


def test_compiling_reads_no_clock() -> None:
    """AD-17: ``today`` is an input. A clock read in pure code is the determinism gate
    failing quietly on a date boundary rather than in a test."""
    offenders = [
        f"{path.relative_to(PACKAGE_ROOT).as_posix()}:{node.lineno}"
        for path, tree in _modules(PACKAGE_ROOT / "compile")
        for node in ast.walk(tree)
        if isinstance(node, ast.Attribute)
        and node.attr in {"today", "now", "utcnow", "time", "monotonic"}
        and isinstance(node.value, ast.Name)
        and node.value.id in {"date", "datetime", "time", "clock"}
    ]
    assert not offenders, "compile/ reads a clock: " + ", ".join(offenders)


def test_the_catalogue_port_cannot_return_a_figure_a_period_or_a_row() -> None:
    """"Before any data access", made structural.

    The binder holds one port, and these are all of its methods. None of them can return
    a value, a row, or a period that exists in the data, so a binder cannot consult the
    newest row even by accident -- which is the signal FR-4 and FR-5 exist to overrule.
    """
    surface = {name for name in vars(CataloguePort) if not name.startswith("_")}
    assert surface == {
        "details_named",
        "default_grain",
        "published_grains",
        "country_named",
        # A count of words over the published *names*, which binding already reads. It
        # returns an int and can express no figure, period or row, so it widens the
        # surface without weakening the claim above -- admitted deliberately, because a
        # method that could return data must never be added here by reflex.
        "longest_name_words",
    }


def test_compile_imports_no_adapter_and_no_later_layer() -> None:
    """AD-2 at the module level, so a failure names the import rather than the contract."""
    forbidden = ("askai.adapters", "askai.execute", "askai.assemble", "askai.narrate")
    offenders = [
        f"{path.relative_to(PACKAGE_ROOT).as_posix()}:{node.lineno} {name}"
        for path, tree in _modules(PACKAGE_ROOT / "compile")
        for node in ast.walk(tree)
        if isinstance(node, ast.ImportFrom)
        for name in [node.module or ""]
        if name.startswith(forbidden)
    ]
    assert not offenders, "compile/ reaches past its layer: " + ", ".join(offenders)


# --------------------------------------------------------- AD-19: one ladder, one binder


def test_the_precedence_in_code_is_the_precedence_in_the_rules() -> None:
    """AD-19's ladder is stated as data; the binders walk it in that order."""
    assert tuple(step.value for step in Precedence) == rules().value(
        BindingRule.PRECEDENCE.value, "order"
    )


def test_every_spec_field_has_a_binder_and_no_field_has_two() -> None:
    """The set of owned fields is read off ``QuerySpec`` itself, so a field added to the
    spec without a binder fails here instead of defaulting to whatever a binder forgot."""
    assert tuple(field.value for field in SpecField) == bindable_fields()


def test_a_missing_binder_is_refused() -> None:
    account = compiled("What was inflation in April 2026?")
    with pytest.raises(ValueError, match="exactly one binder"):
        CompiledQuestion(spec=account.spec, bindings=account.bindings[1:])


def test_two_binders_for_one_field_are_refused() -> None:
    account = compiled("What was inflation in April 2026?")
    twice = (*account.bindings, account.bindings[0])
    with pytest.raises(ValueError, match="exactly one binder"):
        CompiledQuestion(spec=account.spec, bindings=twice)


def test_a_binding_that_disagrees_with_the_spec_is_refused() -> None:
    """The account and the spec are one statement. A record claiming a field was bound
    while the spec carries ``Unbound`` would make the record decorative."""
    account = compiled("What is the price of tea?")
    lying = tuple(
        Binding(field=binding.field, precedence=Precedence.RULE_DEFAULT, bound_by=BoundBy.RULE)
        if binding.field is SpecField.DETAIL
        else binding
        for binding in account.bindings
    )
    with pytest.raises(ValueError, match="one statement"):
        CompiledQuestion(spec=account.spec, bindings=lying)


def test_a_bound_field_with_no_binder_is_refused() -> None:
    with pytest.raises(ValueError, match="bound by someone"):
        Binding(field=SpecField.MEASURE, precedence=Precedence.RULE_DEFAULT, bound_by=None)


def test_named_in_question_outranks_history_and_the_rule_default() -> None:
    account = compiled(
        "What was Real GDP in 2025?", history=("What was inflation in April 2026?",)
    )
    assert account.spec.detail == Bound("D-REAL-GDP")
    assert account.by_field[SpecField.DETAIL].precedence is Precedence.NAMED_IN_QUESTION
    assert account.by_field[SpecField.DETAIL].bound_by is BoundBy.READER


def test_history_outranks_the_rule_default_and_only_where_the_question_is_silent() -> None:
    """A follow-up overrides only the fields its own question names (AD-19)."""
    account = compiled("What about 2022?", history=("What was Real GDP in 2025?",))
    assert account.spec.detail == Bound("D-REAL-GDP")
    assert account.spec.period == Bound(Exact(Period("2022")))
    assert account.by_field[SpecField.DETAIL].precedence is Precedence.INHERITED_FROM_HISTORY
    assert account.by_field[SpecField.PERIOD].precedence is Precedence.NAMED_IN_QUESTION


def test_an_earlier_unbound_field_is_not_inherited() -> None:
    """Carrying "the reader was not specific enough" forward would answer this question
    with the previous one's ambiguity."""
    account = compiled("What about 2022?", history=("What is the price of tea?",))
    assert isinstance(account.spec.detail, Unbound)
    assert account.by_field[SpecField.DETAIL].precedence is Precedence.UNBOUND


def test_the_rule_default_applies_when_nothing_named_and_nothing_inherited() -> None:
    account = compiled("What was inflation in April 2026?")
    assert account.spec.measure == Bound(default_measure())
    assert account.spec.operation == Bound(default_operation())
    assert account.spec.country_scope == Bound(default_country_scope())
    for field in (SpecField.MEASURE, SpecField.OPERATION, SpecField.COUNTRY_SCOPE):
        assert account.by_field[field].precedence is Precedence.RULE_DEFAULT
        assert account.by_field[field].bound_by is BoundBy.RULE


def test_unbound_is_the_last_rung_and_carries_a_stated_cause() -> None:
    account = compiled("What is the price of tea?")
    detail = account.spec.detail
    assert isinstance(detail, Unbound)
    assert detail.reason.startswith(UnboundReason.NO_DETAIL_NAMED.value)
    assert account.by_field[SpecField.DETAIL].bound_by is None
    assert not account.is_answerable


def test_a_name_two_details_share_is_refused_rather_than_chosen_between() -> None:
    """257 of 320 published names are ambiguous; picking one is Epic 2's job and is
    structural before it is semantic (AD-25). Epic 1 states the ambiguity."""
    detail = compiled("What is the employment rate?").spec.detail
    assert isinstance(detail, Unbound)
    assert detail.reason.startswith(UnboundReason.DETAIL_NAME_IS_SHARED.value)
    assert "D-SHARED-ONE" in detail.reason and "D-SHARED-TWO" in detail.reason


