"""Story 1.11: a named detail is bound to a frozen ``QuerySpec``, once, before the data.

The story's acceptance criteria are five claims, and each has a section below:

1. **AD-1** -- exactly one frozen spec per answerable question, produced before any data
   access, and no layer past ``compile/`` can set, widen or reinterpret a field.
2. **AD-19** -- one ladder per field (named-in-question, inherited-from-history, rule
   default, ``Unbound``), walked before the spec is constructed, with exactly one binder
   owning each field.
3. **FR-4, FR-5, FR-6** -- a named grain beats every other signal including the newest
   row's; an unnamed grain takes the detail's *declared* default; a grain the detail does
   not publish is stated rather than swapped for a neighbour.
4. **FR-10, FR-11b** -- no country named means national scope, which is a query shape and
   never a country filter value.
5. **FR-14 and NFR-1/AD-17** -- every field records whose authority it carries, no field
   is bound by a model in this epic, and the same inputs compile to an identical spec.

Several of these are asserted structurally -- by a scan, or by a type that cannot
represent the violation -- rather than by example, because the defects they exist to
prevent are all defects of *reach*: some later layer that could touch a field, or a
binder that could see a row. An example shows it did not happen this time.
"""

