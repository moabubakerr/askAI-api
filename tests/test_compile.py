        CatalogueDetail(
            detail_id="D-SOLAR",
            names=("Percentage of energy generated by solar",),
        ),
        CatalogueDetail(detail_id="D-SHARED-ONE", names=("Employment Rate",)),
        CatalogueDetail(detail_id="D-SHARED-TWO", names=("Employment Rate",)),
