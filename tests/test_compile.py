def test_every_corpus_entry_compiles_to_a_query_spec() -> None:
    """The seam is live: if ``run_entry`` stopped compiling anything, this goes red.

    Compiled against the empty catalogue the runner uses, so it asserts what the binder
    owns -- totality, one binder per field, determinism -- on every committed entry, with
    no database anywhere.
    """
    entries = load_corpus()
    assert entries, "the corpus is empty; there is nothing to compile"
    for entry in entries:
        asked = entry.data["question"]
        for language, text in sorted(asked.items()):
            account = compile_question(
                CompileInput(question=text, today=entry.data["today"]), EMPTY_CATALOGUE
            )
            assert account.spec.today == entry.data["today"], f"{entry.source} {language}"
            assert len(account.bindings) == len(bindable_fields())


